/**
 * Station domain models (plan.md sections 3 and 17.5).
 *
 * Station data may come only from a verified, licensed dataset
 * (addbeforerelease.txt section 9). Display names stay in the provider's
 * official form; aliases are included ONLY when the data source defines
 * them (plan.md section 3.4). See docs/decisions.md DEC-006.
 */

import type { EntityId, GeoPoint, ISODateTime } from './common';
import type { InformationProvenance } from './provenance';

export interface Station {
  id: EntityId;
  /** Official display name exactly as supplied by the data source (typically Bulgarian). */
  name: string;
  /** Alternate display name in Latin script / English, only if the dataset provides it. */
  alternateName?: string;
  /**
   * Searchable alternative spellings — only when defined by the data source
   * and the licence permits them (plan.md section 3.4).
   */
  aliases?: readonly string[];
  /** ISO 3166-1 alpha-2 country code; Bulgarian stations use 'BG'. */
  countryCode: string;
  /** Present only when the licensed dataset includes coordinates. */
  location?: GeoPoint;
  /** Set when the dataset distinguishes stops/halts/stations; verbatim from the source. */
  kind?: string;
  provenance: InformationProvenance;
}

/** A query against the station directory (used by the station picker and the map list). */
export interface StationQuery {
  /**
   * Free text, Cyrillic and/or Latin, possibly mixed case. Matching is
   * provider-defined: exact, prefix and alias matching are mapped in
   * services/ — the UI only passes raw text (addbeforerelease.txt section 8:
   * Cyrillic and Latin search both work, incl. mixed input).
   */
  text?: string;
  /** Optional bounding box for "nearby"/map filtering. Requires location permission only for the nearby feature. */
  near?: GeoPoint;
  /** Max results to return; provider applies a sane default when omitted. */
  limit?: number;
}

/**
 * Versioned station directory as cached on-device (plan.md section 3.7,
 * addbeforerelease.txt section 7 "offline caching of static station data
 * with expiry and stale labels").
 */
export interface StationDirectory {
  /** Directory revision from the data source, when supplied; otherwise a content hash generated by the service layer. */
  version: string;
  stations: readonly Station[];
  /** When this directory copy was fetched. */
  fetchedAt: ISODateTime;
  /** Freshness window end; after this the copy is shown as `cached-stale`. */
  expiresAt: ISODateTime;
  /** Attribution text required by the data source licence; rendered in the UI. Empty only if the licence requires none. */
  attribution?: string;
}
